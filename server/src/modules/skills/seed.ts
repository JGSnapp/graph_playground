const GRAPH_LAYOUT = `# Построение графа

Задача: связная структура, где смысл в связях — схема, алгоритм, пайплайн, дерево,
вики, карта зависимостей, диаграмма состояний, модель данных.

Главное правило: **расстановку узлов считает board_arrange_graph, а не ты**.
Пересечения определяются порядком узлов внутри слоя, а не изгибами линий: на замере
ручная расстановка дала 50 пересечений, послойная на том же графе — ноль, и ни один
параметр роутера этого не менял. Твоя работа — описать граф, а не подбирать координаты.

## Шаг 1. Опиши граф словами, до создания артефактов

Выпиши для себя: список узлов, список рёбер (от кого к кому), что здесь основной
поток, и какие узлы образуют подсистемы (группы). Группы понадобятся на шаге 4.

## Шаг 2. Создай узлы, не мучаясь с координатами

Ставь узлы просто и без наложений: сетка с шагом 320 по x и 240 по y.
Этого достаточно — финальные координаты посчитает раскладка.

- artifact_create с явными x, y; ширину и высоту задавай так, чтобы текст влезал
  (240×180 для заметки в 4-6 строк, больше — если текста больше).
- Если тул отказал из-за наложения — просто возьми следующую свободную клетку сетки.
- Не трать вызовы на «красивую» первоначальную расстановку: её всё равно пересчитают.

## Шаг 3. Создай ВСЕ стрелки

- arrow_create без fromSide/toSide и без fromOffset/toOffset. Стороны и порты
  выберет раскладка; если задать их сейчас, они будут подобраны под временные координаты.
- Подписи (label) задавай сразу — раскладке нужно знать, что им понадобится место.
- Если тул вернул поле adjustments — он сам поправил порт или добавил перпендикулярный
  изгиб. Это нормально и не требует переделки.
- Второстепенную связь между далёкими по смыслу узлами лучше не рисовать вовсе:
  упомяни её словами в тексте узла.

## Шаг 4. Один раз board_arrange_graph

Вызови его, когда созданы все узлы и все стрелки.

Что значит каждый параметр — в описании самого тула; здесь только выбор:
direction оставляй auto, groups задавай при подсистемах, lockIds — для того, что
стояло на доске до тебя.

## Шаг 5. Проверь и правь

1. board_check_intersections — смотри на quality.score, counts и verdict.
2. **Не нравится раскладка целиком — вызови board_arrange_graph ещё раз с другими
   параметрами.** Это дёшево и почти всегда лучше ручной перестановки. Что именно
   менять под какой симптом — в поле tuning его же ответа.
3. Не нравится одна деталь — правь только её:
   - текст не влез — artifact_update с большей высотой;
   - один узел стоит неудачно — artifact_rank_placements, затем artifact_move,
     затем board_route_arrows для стрелок этого узла;
   - остались мёртвые изгибы после ручных сдвигов — board_clean_arrows.
4. Останавливайся, когда ok=true, либо когда два прохода подряд не улучшили cost,
   либо после 4 проходов. Пересечения стрелок на плотной схеме — норма:
   у графа с десятком связей планарной укладки обычно не существует.

### Чего никогда не делать при недовольстве раскладкой

**Не удаляй связи, чтобы создать их заново.** Рёбра те же, слои те же, результат
тот же. Замерено: такой цикл съел 56% токенов прогона и уткнулся в лимит итераций
с тем же качеством, что было на девятой.

Порядок отхода, если результат не устраивает: **другие параметры раскладки →
точечная правка одного узла → и только потом что-то ещё.**

## Шаг 6. Ответ

Коротко: какая структура получилась, какое направление выбрала раскладка,
сколько осталось пересечений и итоговая оценка качества.

## Когда пользователь просит своё расположение

Всё выше — это порядок по умолчанию, а не запрет. Просьба пользователя главнее.

- Просит поставить конкретный блок в конкретное место — ставь туда и не трогай
  раскладкой: передай его id в lockIds, тогда композиция построится вокруг него.
- Просит разложить только новую часть, не трогая старую — nodeIds со списком
  новых узлов. Всё, что не в списке, останется на месте.
- Просит конкретное крепление стрелки (эта сторона, эта точка, такой изгиб) —
  arrow_create или arrow_update с exact=true. Тул сохранит всё как задано и
  только предупредит, если линия ляжет неудачно.
- Просит наложить блоки — acceptOverlap=true; перекрытие помечается как
  задуманное и в оценку качества больше не попадает.
- Просит расставить всё вручную и раскладка не нужна — просто не вызывай
  board_arrange_graph. Скажи, какая вышла оценка, и оставь как есть.

Низкая оценка после такой просьбы — не повод переделывать. Отметь её словами.

## Чего не делать по своей инициативе

- Не подбирать координаты узлов вручную до раскладки, если пользователь об этом
  не просил.
- Не задавать стороны и порты стрелок до раскладки: они будут подобраны под
  временные координаты.
- Не вызывать board_arrange_graph повторно после каждой мелкой правки —
  он пересобирает всю композицию.
- Не добавлять изгибы «для красоты».
- Не переделывать за пользователем то, что он попросил явно.`;

